#!/bin/bash
# Render design/changelog/*.md into one view, newest first.
#   changelog-render.sh            prints to stdout
#   changelog-render.sh -o FILE    writes FILE (design/CHANGELOG.md is the convention; it is generated and git-ignored)
#   changelog-render.sh -n 20      only the newest 20 entries
set -eu
out=""; limit=0
while [ $# -gt 0 ]; do
  case "$1" in
    -o) out="$2"; shift 2 ;;
    -n) limit="$2"; shift 2 ;;
    *) echo "usage: changelog-render.sh [-o FILE] [-n COUNT]" >&2; exit 1 ;;
  esac
done
root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
dir="$root/design/changelog"
[ -d "$dir" ] || { echo "no $dir" >&2; exit 1; }
render() {
  echo "<!-- generated by changelog-render.sh from design/changelog/; do not edit, do not commit -->"
  echo "# Design changelog"
  echo
  n=0
  # Newest first by name; a glob loop, so paths with spaces survive.
  for f in "$dir"/*.md; do [ -e "$f" ] && printf '%s\n' "$f"; done | sort -r | while IFS= read -r f; do
    n=$((n + 1))
    [ "$limit" -gt 0 ] && [ "$n" -gt "$limit" ] && break
    cat "$f"; echo; echo "---"; echo
  done
}
if [ -n "$out" ]; then render > "$out"; echo "wrote $out"; else render; fi
